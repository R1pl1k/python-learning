import random    # подключение модуля случаных числе
secret: int = random.randint(1, 100)    # Числа будут от 1 до 100
attempts: int = 0     # Cчетчик попыток 0

while True:    # Повторяй пока не угадаю
    number: int = int (input("Какое число будет?") )    # Введите число пользователя
    attempts += 1    # прибавить 1 к счётчику попыток
    if secret > number:    # Если число больше пользователя
        print("Больше")      #выводит инф что нужно больше
    elif secret < number:    # Если число меньше пользователя
        print("Меньше")   #выводит инф что нужно меньше
    else:# Если число угадано пользователем
        print(f"Вы угадали число: {secret}, число попыток : {attempts}")     #выводит инф что это верное число и сколько ушло попыток
        break    #Остановись