password = "" # пароль = "" (пусто, человек ещё ничего не вводил) 
attempts = 0 # попыток = 0 
while password !=1234 and attempts<3 :    # Повторять, пока пароль не равен 1234 и попыток меньше 3 
    password: int = int(input("ВВедите пароль"))# Вводит пароль← что делает человек 
    attempts +=1 # Попыток +1 ← что делает охранник со счётчиком 
if password==1234:# Если пароль равен 1234 
    print(f"Проходите, число попыток: {attempts}")    # Проходите
else:  # Иначе 
    print(f"Вы не можете пройти")  # Вы не можете пройти